using System.Text;
using Master.Configuration;
using Master.Models;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Data.SqlClient;

namespace Master.Controllers;

// Shared plumbing for the CRM module: metadata-driven
// field loading, grid joins, counts, lead numbering and
// the history audit trail.
public abstract class CrmControllerBase : Controller
{
    protected readonly IConfiguration Configuration;
    protected readonly DynamicTableService TableService;

    protected CrmControllerBase(
        IConfiguration configuration,
        DynamicTableService tableService)
    {
        Configuration = configuration;
        TableService = tableService;
    }

    protected abstract string TableName { get; }

    protected bool IsAjax =>
        DynamicTableService.IsAjaxRequest(Request);

    protected string? LoggedInUserId =>
        DynamicTableService.GetLoggedInUserId(User);

    protected async Task<SqlConnection> OpenAsync()
    {
        string? connectionString =
            Configuration.GetConnectionString("DefaultConnection");

        if (string.IsNullOrWhiteSpace(connectionString))
        {
            throw new InvalidOperationException(
                "Database connection string is missing.");
        }

        var connection = new SqlConnection(connectionString);

        await connection.OpenAsync();

        return connection;
    }

    // Well-known system columns get their behaviour pinned
    // here so the views/controllers can stay generic.
    protected virtual void ApplyConventions(
        List<MasterColumnViewModel> fields)
    {
        foreach (var field in fields)
        {
            if (field.Name.Equals(
                    "EntryOn",
                    StringComparison.OrdinalIgnoreCase))
            {
                field.Editable = false;
                field.AutoWrite = "now";
                field.Control = "input";
                field.InputType = "text";
            }
            else if (field.Name.Equals(
                         "LeadNo",
                         StringComparison.OrdinalIgnoreCase))
            {
                // Generated by the app on insert.
                field.Editable = false;
                field.ShowInTable = true;
            }
            else if (field.Name.Equals(
                         "DoneOn",
                         StringComparison.OrdinalIgnoreCase))
            {
                // Set by the Mark Done action only.
                field.Editable = false;
            }
        }
    }

    protected async Task<List<MasterColumnViewModel>> LoadFieldsAsync(
        SqlConnection connection)
    {
        List<MasterColumnViewModel> fields =
            await TableService.GetTableFieldsAsync(
                connection,
                TableName);

        ApplyConventions(fields);

        return fields;
    }

    // ============================================
    // GRID
    // LEFT JOIN is used deliberately: CRM foreign keys
    // (State, Client, AssignedTo, Lead) are optional, so
    // an INNER JOIN would silently drop rows.
    // ============================================

    protected async Task<List<MasterRowViewModel>> LoadGridAsync(
        SqlConnection connection,
        List<MasterColumnViewModel> fields,
        string? search,
        string? extraWhere = null,
        string? tableName = null)
    {
        string sourceTable = tableName ?? TableName;

        var selectParts = new List<string>();
        var joinClauses = new List<string>();
        var searchParts = new List<string>();
        var joinAliases =
            new Dictionary<string, string>(
                StringComparer.OrdinalIgnoreCase);

        int joinIndex = 0;

        foreach (var field in fields)
        {
            if (field.LookupKey != null
                && TableService.TryGetLookupDisplayColumn(
                    field.LookupKey,
                    out string displayColumn))
            {
                string joinKey = $"{field.LookupKey}|{field.Name}";

                if (!joinAliases.TryGetValue(
                        joinKey,
                        out string? alias))
                {
                    alias = $"j{joinIndex++}";

                    joinAliases[joinKey] = alias;

                    joinClauses.Add(
                        $" LEFT JOIN [{field.LookupKey}] {alias} " +
                        $"ON {alias}.[{field.LookupRefColumn ?? "Id"}] " +
                        $"= s.[{field.Name}]");
                }

                selectParts.Add(
                    $"{alias}.[{displayColumn}] AS [{field.Name}]");

                if (field.Editable
                    && field.Control == "select")
                {
                    selectParts.Add(
                        $"s.[{field.Name}] AS [{field.Name}_key]");
                }

                searchParts.Add(
                    $"{alias}.[{displayColumn}] " +
                    $"LIKE '%' + @Search + '%'");
            }
            else
            {
                selectParts.Add($"s.[{field.Name}]");

                if (DynamicTableService.IsText(field.SqlType))
                {
                    searchParts.Add(
                        $"s.[{field.Name}] " +
                        $"LIKE '%' + @Search + '%'");
                }
            }
        }

        string idColumn =
            fields.FirstOrDefault(f => f.IsPrimaryKey)?.Name
            ?? "Id";

        var sql = new StringBuilder();

        sql.Append("SELECT ");
        sql.Append(string.Join(", ", selectParts));
        sql.Append($" FROM [{sourceTable}] s");

        foreach (string join in joinClauses)
        {
            sql.Append(join);
        }

        var whereParts = new List<string>();

        if (searchParts.Count > 0)
        {
            whereParts.Add(
                "(@Search = '' OR "
                + string.Join(" OR ", searchParts)
                + ")");
        }
        else
        {
            whereParts.Add("@Search = ''");
        }

        if (!string.IsNullOrWhiteSpace(extraWhere))
        {
            whereParts.Add("(" + extraWhere + ")");
        }

        sql.Append(" WHERE " + string.Join(" AND ", whereParts));

        sql.Append($" ORDER BY s.[{idColumn}] DESC");

        var rows = new List<MasterRowViewModel>();

        using SqlCommand command =
            new SqlCommand(sql.ToString(), connection);

        command.CommandTimeout = 0;

        command.Parameters.Add(
            new SqlParameter(
                "@Search",
                System.Data.SqlDbType.NVarChar,
                100)
            {
                Value = search?.Trim() ?? ""
            });

        using SqlDataReader reader =
            await command.ExecuteReaderAsync();

        while (await reader.ReadAsync())
        {
            var row = new MasterRowViewModel();

            foreach (var field in fields)
            {
                row.Values[field.Name] =
                    DynamicTableService.FormatCellValue(
                        field,
                        reader[field.Name]);

                if (field.LookupKey != null
                    && field.Editable
                    && field.Control == "select"
                    && TableService.TryGetLookupDisplayColumn(
                        field.LookupKey,
                        out _))
                {
                    object? keyValue =
                        reader[$"{field.Name}_key"];

                    row.Values[$"{field.Name}_key"] =
                        keyValue == DBNull.Value
                            ? ""
                            : keyValue.ToString() ?? "";
                }
                else if (field.Editable)
                {
                    // Input-friendly raw value for the edit modal
                    // (ISO dates/times that <input> accepts).
                    row.Values[$"{field.Name}_edit"] =
                        BuildEditValue(field, reader[field.Name]);
                }
            }

            rows.Add(row);
        }

        return rows;
    }

    protected async Task<int> ScalarIntAsync(
        SqlConnection connection,
        string sql,
        params (string Name, object? Value)[] parameters)
    {
        using SqlCommand command =
            new SqlCommand(sql, connection);

        command.CommandTimeout = 0;

        foreach (var (name, value) in parameters)
        {
            command.Parameters.AddWithValue(name, value ?? DBNull.Value);
        }

        object? result = await command.ExecuteScalarAsync();

        return result == null || result == DBNull.Value
            ? 0
            : Convert.ToInt32(result);
    }

    // ============================================
    // LEAD NUMBER  ->  CRM-0001, CRM-0002 ...
    // ============================================

    protected async Task<string> GenerateLeadNoAsync(
        SqlConnection connection)
    {
        const string query = @"
            SELECT ISNULL(MAX(
                CASE
                    WHEN ISNUMERIC(
                        REPLACE(LeadNo, 'CRM-', '')) = 1
                    THEN CAST(
                        REPLACE(LeadNo, 'CRM-', '') AS INT)
                    ELSE 0
                END), 0) + 1
            FROM [CrmLead]
            WHERE LeadNo LIKE 'CRM-%'";

        int next = await ScalarIntAsync(connection, query);

        return $"CRM-{next:D4}";
    }

    // ============================================
    // HISTORY (audit trail)
    // ============================================

    protected async Task WriteHistoryAsync(
        SqlConnection connection,
        int leadId,
        string eventType,
        string? oldValue,
        string? newValue,
        string? remarks)
    {
        const string query = @"
            INSERT INTO [CrmLeadHistory]
                ([LeadId], [EventDate], [EventType],
                 [OldValue], [NewValue], [Remarks], [UserId])
            VALUES
                (@LeadId, GETDATE(), @EventType,
                 @OldValue, @NewValue, @Remarks, @UserId)";

        using SqlCommand command =
            new SqlCommand(query, connection);

        command.CommandTimeout = 0;

        command.Parameters.AddWithValue("@LeadId", leadId);
        command.Parameters.AddWithValue("@EventType", eventType);
        command.Parameters.AddWithValue(
            "@OldValue",
            (object?)NullIfEmpty(oldValue) ?? DBNull.Value);
        command.Parameters.AddWithValue(
            "@NewValue",
            (object?)NullIfEmpty(newValue) ?? DBNull.Value);
        command.Parameters.AddWithValue(
            "@Remarks",
            (object?)NullIfEmpty(remarks) ?? DBNull.Value);

        command.Parameters.AddWithValue(
            "@UserId",
            int.TryParse(LoggedInUserId, out int uid)
                ? uid
                : (object)DBNull.Value);

        await command.ExecuteNonQueryAsync();
    }

    protected static string? NullIfEmpty(string? value) =>
        string.IsNullOrWhiteSpace(value) ? null : value.Trim();

    private static string BuildEditValue(
        MasterColumnViewModel field,
        object value)
    {
        if (value == null || value == DBNull.Value)
        {
            return "";
        }

        if (field.Type == "date")
        {
            var date = Convert.ToDateTime(value);

            return field.InputType switch
            {
                "time" => date.ToString("HH:mm"),
                "datetime-local" => date.ToString("yyyy-MM-ddTHH:mm"),
                _ => date.ToString("yyyy-MM-dd")
            };
        }

        return value.ToString() ?? "";
    }

    protected static string ToDisplay(object? value) =>
        value == null || value == DBNull.Value
            ? ""
            : Convert.ToString(value)?.Trim() ?? "";

    // ============================================
    // GENERIC FORM VALIDATION
    // ============================================

    protected string? ValidateRequired(
        IEnumerable<MasterColumnViewModel> fields,
        IFormCollection form) =>
        TableService.ValidateRequiredFields(fields, form);

    // ============================================
    // GENERIC INSERT / UPDATE (metadata driven)
    // ============================================

    protected async Task<int> InsertAsync(
        SqlConnection connection,
        List<MasterColumnViewModel> fields,
        IFormCollection form,
        Dictionary<string, string>? overrides = null,
        Dictionary<string, object?>? extraColumns = null)
    {
        var formFields = fields.Where(f => f.Editable).ToList();

        var insertColumns = new List<string>();
        var placeholders = new List<string>();

        using var command = new SqlCommand
        {
            Connection = connection,
            CommandTimeout = 0
        };

        foreach (var field in formFields)
        {
            if (field.AutoWrite != null)
            {
                continue;
            }

            string raw =
                overrides != null
                && overrides.TryGetValue(field.Name, out string? inline)
                    ? inline
                    : form[field.Name].ToString();

            insertColumns.Add(field.Name);
            placeholders.Add($"@{field.Name}");

            TableService.AddParameter(command, field, raw);
        }

        foreach (var auto in fields.Where(f => f.AutoWrite != null))
        {
            if (auto.AutoWrite == "auth-user"
                && int.TryParse(LoggedInUserId, out int uid))
            {
                insertColumns.Add(auto.Name);
                placeholders.Add($"@{auto.Name}");

                command.Parameters.Add(
                    new SqlParameter($"@{auto.Name}", System.Data.SqlDbType.Int)
                    {
                        Value = uid
                    });
            }
            else if (auto.AutoWrite == "true")
            {
                insertColumns.Add(auto.Name);
                placeholders.Add("1");
            }
            else if (auto.AutoWrite == "now")
            {
                insertColumns.Add(auto.Name);
                placeholders.Add("GETDATE()");
            }
        }

        if (extraColumns != null)
        {
            foreach (var kv in extraColumns)
            {
                insertColumns.Add(kv.Key);
                placeholders.Add($"@{kv.Key}");

                command.Parameters.AddWithValue($"@{kv.Key}", kv.Value ?? DBNull.Value);
            }
        }

        command.CommandText =
            $"INSERT INTO [{TableName}] "
            + $"({string.Join(", ", insertColumns)}) "
            + $"VALUES ({string.Join(", ", placeholders)}); "
            + "SELECT CAST(SCOPE_IDENTITY() AS INT);";

        object? result = await command.ExecuteScalarAsync();

        return result == null || result == DBNull.Value
            ? 0
            : Convert.ToInt32(result);
    }

    protected async Task<int> UpdateAsync(
        SqlConnection connection,
        List<MasterColumnViewModel> fields,
        IFormCollection form,
        int id,
        Dictionary<string, string>? overrides = null)
    {
        var idColumn =
            fields.FirstOrDefault(f => f.IsPrimaryKey)?.Name ?? "Id";

        var editFields = fields
            .Where(f => f.Editable && !f.CreateOnly)
            .ToList();

        var setParts = new List<string>();

        using var command = new SqlCommand
        {
            Connection = connection,
            CommandTimeout = 0
        };

        command.Parameters.Add(
            new SqlParameter("@Id", System.Data.SqlDbType.Int)
            {
                Value = id
            });

        foreach (var field in editFields)
        {
            if (field.AutoWrite != null)
            {
                continue;
            }

            string raw =
                overrides != null
                && overrides.TryGetValue(field.Name, out string? inline)
                    ? inline
                    : form[field.Name].ToString();

            setParts.Add($"[{field.Name}] = @{field.Name}");

            TableService.AddParameter(command, field, raw);
        }

        foreach (var auto in fields.Where(
                     f => f.AutoWrite == "true"))
        {
            setParts.Add($"[{auto.Name}] = 1");
        }

        if (setParts.Count == 0)
        {
            return 0;
        }

        command.CommandText =
            $"UPDATE [{TableName}] SET "
            + string.Join(", ", setParts)
            + $" WHERE [{idColumn}] = @Id";

        return await command.ExecuteNonQueryAsync();
    }
}
